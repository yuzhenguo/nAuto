# 2. 리뷰 생성 로직 (상품당 100개, 총 300개)
all_rows = []
total_counter = 1

for prod in products:
    generated_reviews = set()
    
    while len(generated_reviews) < 100:
        intro = random.choice(prod["intro"])
        body = random.choice(prod["body"])
        outro = random.choice(prod["outro"])
        
        # 길이와 형태 다양화 (단문, 중문, 장문)
        rand_val = random.random()
        if rand_val < 0.25:
            content = f"{intro} {outro}"
        elif rand_val < 0.65:
            content = f"{intro} {body}"
        else:
            content = f"{intro} {body} {outro}"
            
        if content not in generated_reviews:
            generated_reviews.add(content)
            
            # 별점 분포 (5점 약 88%, 4점 약 12%)
            score = 5 if random.random() > 0.12 else 4
            
            all_rows.append({
                "번호": total_counter,
                "상품명": prod["name"],
                "선택 옵션": prod["option"],
                "별점": score,
                "리뷰 내용": content
            })
            total_counter += 1

# 3. 데이터프레임 변환 및 엑셀 저장
df = pd.DataFrame(all_rows)
output_filename = "naver_reviews_300.xlsx"

# 엑셀 열 너비 자동 조정 저장
with pd.ExcelWriter(output_filename, engine='openpyxl') as writer:
    df.to_excel(writer, index=False, sheet_name='리뷰목록')
    worksheet = writer.sheets['리뷰목록']
    
    # 가독성을 위한 컬럼 너비 지정
    worksheet.column_dimensions['A'].width = 8   # 번호
    worksheet.column_dimensions['B'].width = 38  # 상품명
    worksheet.column_dimensions['C'].width = 30  # 선택 옵션
    worksheet.column_dimensions['D'].width = 8   # 별점
    worksheet.column_dimensions['E'].width = 75  # 리뷰 내용

print(f"총 {len(df)}건의 리뷰가 '{output_filename}' 파일로 저장되었습니다.")